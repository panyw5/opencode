const dict: Record<string, Messages> = { en, zh, zht, ko, de, es, fr, da, ja, pl, ru, ar, no, br, th, bs, tr }

export function messages(locale: string): Messages {
  const [base = "", ...tags] = locale.toLowerCase().replaceAll("_", "-").split("-")
  if (base === "zh") return tags.some((tag) => ["hant", "tw", "hk", "mo"].includes(tag)) ? zht : zh
  if (base === "pt") return br
  if (base === "nb" || base === "nn") return no
  return Object.prototype.hasOwnProperty.call(dict, base) ? dict[base] : en
}
